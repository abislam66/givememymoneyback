// Runs the rules engine on both test sets and compares each to its answer key:
//   - Generated set: data/cases/ + data/answer_key.json (built by `npm run generate`)
//   - Hand-written edge cases: data/handwritten/ (written by hand, independent of the generator)
//   npm run score
// Writes data/scoreboard.json for the UI and public/demo-data.js for demo mode.

const fs = require('fs');
const path = require('path');
const assert = require('assert');
const { check, normalize } = require('../src/rules');
const { buildLetter, buildCallScript } = require('../src/letter');
const { explainTerm, explainFinding, GLOSSARY } = require('../src/explain');

const DATA = path.join(__dirname, '..', 'data');
const CASES_DIR = path.join(DATA, 'cases');
const HW_DIR = path.join(DATA, 'handwritten');
const TOL = 0.5;

function loadCases(dir) {
  if (!fs.existsSync(dir)) throw new Error(`No test cases in ${dir}. Run "npm run generate" first.`);
  return fs.readdirSync(dir).filter((f) => f.endsWith('.json') && f !== 'answer_key.json').sort()
    .map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
}

// Match planted errors to found flags by type, and by amount within $0.50.
function compare(planted, found) {
  const remaining = found.map((f) => ({ type: f.type, amount: f.amount }));
  const caught = [];
  const missed = [];
  for (const p of planted) {
    const idx = remaining.findIndex((f) => f.type === p.type && Math.abs(f.amount - p.amount) <= TOL);
    if (idx >= 0) { caught.push(p); remaining.splice(idx, 1); } else missed.push(p);
  }
  return { caught, missed, falseAlarms: remaining };
}

function heroAssertions(c) {
  const r = check(c.bill, c.eob);
  // 1. exactly the two planted flags, with the right amounts, in order
  assert.deepStrictEqual(r.flags.map((f) => [f.type, f.amount]), [['duplicate_charge', 380], ['missing_insurance_payment', 610]], 'hero flags');
  // 2. bill says $1,240, likely owe $250, potential savings $990
  assert.deepStrictEqual(
    { due: r.summary.amount_due, owe: r.summary.likely_owe, pending: r.summary.pending_amount, potential: r.summary.potential_savings },
    { due: 1240, owe: 250, pending: 0, potential: 990 }, 'hero summary');
  // 3. math reads $1,240 − $380 − $610 = $250
  assert.deepStrictEqual(r.math.map((m) => m.amount), [1240, -380, -610, 250], 'hero math');
  // the duplicate points at bill lines 2 and 3 and EOB line index 1
  assert.deepStrictEqual(r.flags[0].evidence, { bill_lines: [2, 3], eob_lines: [1] }, 'hero duplicate evidence');
}

// Demo mode data: the hero case with its full result and explanations, so the demo needs no network.
function writeDemoBundle(hero, scoreboard) {
  const { bill, eob } = normalize(hero.bill, hero.eob);
  const result = check(bill, eob);
  const full = { ...result, letter: buildLetter(bill, eob, result), call_script: buildCallScript(result, bill, eob) };
  const terms = {};
  for (const key of Object.keys(GLOSSARY)) {
    const t = explainTerm(key, { bill, eob });
    terms[key] = { title: t.title, text: t.text, source: 'glossary' };
  }
  for (const l of bill.lines) {
    const t = explainTerm(l.code);
    terms[l.code] = { title: t.title, text: t.text, source: 'glossary' };
  }
  const flags = {};
  for (const f of result.flags) flags[f.id] = { title: f.title, text: explainFinding(f, bill, eob), source: 'glossary' };
  const bundle = { case: { id: hero.id, title: hero.title, profile: hero.profile, bill: hero.bill, eob: hero.eob }, result: full, terms, flags, scoreboard };
  const file = path.join(__dirname, '..', 'public', 'demo-data.js');
  fs.writeFileSync(file, '// Generated by `npm run score`. Hero case data for demo mode (works with no network).\n'
    + `window.SECONDLOOK_DEMO = ${JSON.stringify(bundle)};\n`);
  console.log('Wrote public/demo-data.js');
}

// Score one test set against its answer key and print its table.
function scoreSet(name, cases, key) {
  const rows = [];
  let planted = 0;
  let caughtN = 0;
  let falseN = 0;
  let oweOk = 0;
  for (const c of cases) {
    const k = key[c.id];
    if (!k) throw new Error(`No answer key entry for ${c.id}`);
    const r = check(c.bill, c.eob);
    const cmp = compare(k.errors, r.flags);
    const owe = Math.abs(r.summary.likely_owe - k.expected_owe) <= TOL;
    planted += k.errors.length;
    caughtN += cmp.caught.length;
    falseN += cmp.falseAlarms.length;
    if (owe) oweOk += 1;
    rows.push({
      id: c.id, profile: c.profile ? c.profile.id : null, title: c.title,
      planted: k.errors.map((e) => e.type), found: r.flags.map((f) => f.type),
      missed: cmp.missed.map((e) => e.type), false_alarms: cmp.falseAlarms.map((e) => e.type),
      expected_owe: k.expected_owe, likely_owe: r.summary.likely_owe, owe_correct: owe,
    });
  }

  console.log(`\n=== ${name} ===`);
  const fmt = (a) => (a.length ? a.join(', ') : '-');
  const table = rows.map((r) => ({
    id: r.id, planted: fmt(r.planted), found: fmt(r.found), missed: fmt(r.missed),
    'false alarms': fmt(r.false_alarms), owe: `${r.likely_owe} vs ${r.expected_owe} ${r.owe_correct ? 'ok' : 'WRONG'}`,
  }));
  const cols = Object.keys(table[0]);
  const w = Object.fromEntries(cols.map((c) => [c, Math.max(c.length, ...table.map((t) => String(t[c]).length))]));
  const line = (t) => cols.map((c) => String(t[c]).padEnd(w[c])).join(' | ');
  console.log(line(Object.fromEntries(cols.map((c) => [c, c]))));
  console.log(cols.map((c) => '-'.repeat(w[c])).join('-+-'));
  table.forEach((t) => console.log(line(t)));

  const totals = { cases: cases.length, planted, caught: caughtN, false_alarms: falseN, owe_correct: oweOk };
  console.log(`${name}: caught ${caughtN} of ${planted} planted errors, ${falseN} false alarms, ${oweOk} of ${cases.length} owed amounts correct.`);
  const perfect = caughtN === planted && falseN === 0 && oweOk === cases.length;
  return { name, totals, cases: rows, perfect };
}

function main() {
  const generated = loadCases(CASES_DIR);
  const handwritten = loadCases(HW_DIR);
  const genKey = JSON.parse(fs.readFileSync(path.join(DATA, 'answer_key.json'), 'utf8'));
  const hwKey = JSON.parse(fs.readFileSync(path.join(HW_DIR, 'answer_key.json'), 'utf8'));

  const gen = scoreSet(`Generated set (${generated.length} cases)`, generated, genKey);
  const hw = scoreSet(`Hand-written edge cases (${handwritten.length} cases)`, handwritten, hwKey);

  let heroOk = true;
  try {
    heroAssertions(generated.find((c) => c.id === 'case-01'));
    console.log('\nHero case assertions: 3 of 3 passed.');
  } catch (e) {
    heroOk = false;
    console.log(`\nHero case assertion FAILED: ${e.message}`);
  }

  const sets = [
    { id: 'generated', name: gen.name, totals: gen.totals, cases: gen.cases },
    { id: 'handwritten', name: hw.name, totals: hw.totals, cases: hw.cases },
  ];
  // Top-level totals/cases repeat the generated set for older readers of this file.
  const scoreboard = { generated_at: new Date().toISOString(), hero_ok: heroOk, sets, totals: gen.totals, cases: gen.cases };
  fs.writeFileSync(path.join(DATA, 'scoreboard.json'), `${JSON.stringify(scoreboard, null, 2)}\n`);
  console.log('Wrote data/scoreboard.json');
  writeDemoBundle(generated.find((c) => c.id === 'case-01'), scoreboard);

  console.log(`${gen.name}: ${gen.perfect ? '100%' : 'NOT 100%'}`);
  console.log(`${hw.name}: ${hw.perfect ? '100%' : 'NOT 100%'}`);
  const perfect = gen.perfect && hw.perfect && heroOk;
  console.log(perfect ? 'Scoreboard: 100% on both sets' : 'Scoreboard: NOT 100%');
  if (!perfect) process.exit(1);
}

main();
